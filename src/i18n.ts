export const textos = {
  es: textosEs,
  en: textosEn,
} as const;

export type TextosJuego = typeof textosEs;
export type ClaveI18n = HojasRuta<TextosJuego>;
export type ParamsI18n = Readonly<Record<string, string | number>>;

function resolverRuta(
  obj: unknown,
  partes: readonly string[],
): string | null {
  let actual: unknown = obj;
  for (const parte of partes) {
    if (typeof actual !== 'object' || actual === null || !(parte in actual)) {
      return null;
    }
    actual = (actual as Record<string, unknown>)[parte];
  }
  return typeof actual === 'string' ? actual : null;
}

export function interpolarPlantilla(
  plantilla: string,
  params?: ParamsI18n,
): string {
  if (!params) {
    return plantilla;
  }
  return plantilla.replace(/\{([a-zA-Z0-9_]+)\}/g, (completo, clave: string) => {
    const valor = params[clave];
    return valor !== undefined ? String(valor) : completo;
  });
}

export function t(
  clave: ClaveI18n,
  params?: ParamsI18n,
  idiomaForzado?: Idioma,
): string {
  const idioma = idiomaForzado ?? getAjustes().idioma;
  const partes = clave.split('.');
  const plantilla =
    resolverRuta(textos[idioma], partes) ??
    resolverRuta(textos.es, partes) ??
    clave;
  return interpolarPlantilla(plantilla, params);
}

export function obtenerTextos(idioma?: Idioma): EstructuraTextos<TextosJuego> {
  const activo = idioma ?? getAjustes().idioma;
  return textos[activo] ?? textos.es;
}
